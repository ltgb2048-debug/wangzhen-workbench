function loadState(){
  try{
    const raw=localStorage.getItem(KEY)||localStorage.getItem(oldKey);
    if(!raw) return structuredClone(defaultState);
    const parsed=JSON.parse(raw);
    return {...structuredClone(defaultState),...parsed};
  }catch(e){return structuredClone(defaultState);}
}
function save(){localStorage.setItem(KEY,JSON.stringify(state));}
function byId(id){return document.getElementById(id);}
function esc(s=''){return String(s).replace(/[&<>"']/g,m=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[m]));}
function currentPlan(){return plan.find(x=>x.d===state.day)||plan[0];}

function showPage(name){
  document.querySelectorAll('.page').forEach(x=>x.classList.add('hide'));
  document.querySelectorAll('.nav button').forEach(x=>x.classList.remove('active'));
  byId(name)?.classList.remove('hide');
  document.querySelector(`.nav button[data-page="${name}"]`)?.classList.add('active');
  if(name==='home') renderHome();
  if(name==='learn') renderLearn();
  if(name==='quiz') renderQuiz();
  if(name==='simulate') renderScenarios();
  if(name==='wiki') renderGlossary();
  if(name==='progress') renderProgress();
}

document.querySelectorAll('.nav button').forEach(btn=>btn.addEventListener('click',()=>showPage(btn.dataset.page)));

function renderHome(){
  const p=currentPlan();
  byId('currentTitle').textContent=`Day ${p.d} · ${p.t}`;
  byId('currentSummary').textContent=p.s;
  byId('currentDayNo').textContent=state.day;
  byId('completedDays').textContent=state.done.length;
  const pct=Math.round(state.done.length/15*100);
  byId('overallPct').textContent=pct+'%';
  byId('overallBar').style.width=pct+'%';
  byId('avgScore').textContent=state.scores.length?Math.round(state.scores.reduce((a,b)=>a+b,0)/state.scores.length):0;
  byId('dayGrid').innerHTML=plan.map(x=>`<button class="day-card ${state.done.includes(x.d)?'done':''} ${state.day===x.d?'current':''}" data-day="${x.d}"><span>DAY ${String(x.d).padStart(2,'0')}</span><b>${esc(x.t)}</b><small>${state.done.includes(x.d)?'已完成':'进入学习'}</small></button>`).join('');
  document.querySelectorAll('[data-day]').forEach(btn=>btn.addEventListener('click',()=>{state.day=Number(btn.dataset.day);save();showPage('learn');}));
}

function renderLearn(){
  const p=currentPlan();
  byId('learnDay').textContent=`Day ${p.d} · ${p.t}`;
  byId('learnSummary').textContent=p.s;
  byId('lessonList').innerHTML=p.lessons.map((l,i)=>`<article class="lesson card"><div class="lesson-no">${String(i+1).padStart(2,'0')}</div><div><h3>${esc(l[0])}</h3><p>${esc(l[1])}</p></div></article>`).join('');
  byId('checkList').innerHTML=p.checks.map(c=>`<label><input type="checkbox"> <span>${esc(c)}</span></label>`).join('');
  const done=state.done.includes(p.d);
  byId('dayDoneBtn').textContent=done?'今天已完成 ✓':'完成今天学习';
  byId('dayDoneBtn').onclick=()=>{
    if(!state.done.includes(p.d)) state.done.push(p.d);
    state.done.sort((a,b)=>a-b);
    if(state.day<15) state.day=Math.max(state.day,p.d+1);
    save();
    renderLearn();
    renderHome();
  };
}

function shuffle(arr){return [...arr].sort(()=>Math.random()-.5);}
function renderQuiz(){
  if(!currentQuiz.length) currentQuiz=shuffle(bank).slice(0,10);
  byId('quizList').innerHTML=currentQuiz.map((q,i)=>`<div class="quiz card"><b>${i+1}. ${esc(q.q)}</b><div class="options">${q.a.map((a,j)=>`<label><input type="radio" name="q${i}" value="${j}"> ${esc(a)}</label>`).join('')}</div><small>${esc(q.tag||'')}</small></div>`).join('');
  byId('quizResult').classList.add('hide');
}
byId('refreshQuiz').onclick=()=>{currentQuiz=shuffle(bank).slice(0,10);renderQuiz();};
byId('submitQuiz').onclick=()=>{
  let correct=0,answered=0;
  const mistakes=[];
  currentQuiz.forEach((q,i)=>{
    const pick=document.querySelector(`input[name="q${i}"]:checked`);
    if(pick){answered++; if(Number(pick.value)===q.c) correct++; else mistakes.push(`${i+1}. ${q.q} → 正确：${q.a[q.c]}`);}
  });
  const score=correct*10;
  state.scores.push(score); save();
  const el=byId('quizResult');
  el.classList.remove('hide');
  el.innerHTML=`<h3>${score>=80?'通过':'继续补强'} · ${score}分</h3><p>答对 ${correct}/10，已作答 ${answered}/10。</p>${mistakes.length?`<div class="mistakes"><b>错题复盘</b><br>${mistakes.map(esc).join('<br>')}</div>`:'<p>本组全对，可以换一组继续。</p>'}<p class="muted">注意：题库训练稳定框架。具体年份政策仍需核对当年官方公告。</p>`;
  renderHome();
};

