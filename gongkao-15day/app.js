byId('submitScenario').onclick=()=>{
  if(!activeScenario) return;
  const text=byId('scenarioAnswer').value.trim();
  if(!text){alert('先写下你会怎么接这个学员。');return;}
  const hit=activeScenario.must.filter(k=>text.includes(k));
  const score=Math.min(100,40+hit.length*10+Math.min(20,Math.floor(text.length/40)*5));
  state.scenarioScores.push(score);save();
  const miss=activeScenario.must.filter(k=>!text.includes(k));
  const el=byId('scenarioResult');el.classList.remove('hide');
  el.innerHTML=`<h3>自检 ${score}分</h3><p>${esc(activeScenario.hint)}</p><p><b>已覆盖：</b>${hit.length?hit.map(esc).join('、'):'暂无'}</p><p><b>建议再检查：</b>${miss.length?miss.map(esc).join('、'):'关键点基本覆盖'}</p><p class="muted">这是离线关键词自检，不等于AI真实评价。重点看你有没有补信息、说明依据和保留核验边界。</p>`;
};
