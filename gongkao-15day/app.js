  byId('scenarioWork').classList.remove('hide');
  byId('scenarioTitle').textContent=activeScenario.title;
  byId('scenarioDesc').textContent=activeScenario.desc;
  byId('scenarioAnswer').value='';
  byId('scenarioResult').classList.add('hide');
  byId('scenarioWork').scrollIntoView({behavior:'smooth'});
